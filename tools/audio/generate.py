#!/usr/bin/env python3
"""Generate all site audio with Azure AI Speech (neural voices).

Runs in GitHub Actions (.github/workflows/audio.yml) after `node tools/audio/build_jobs.js`.
The key and region come from the repository secrets AZURE_SPEECH_KEY and AZURE_SPEECH_REGION:
never write them in this file or in the site.

- One British voice for all British English audio, one American voice for GA comparisons.
- Homographs get an SSML <phoneme> with the SSBE IPA (see IPA in build_jobs.js).
- Files are named by a hash of voice + text + pronunciation, so existing files are reused and
  only new or changed items are generated. Unused files are removed.
Outputs:
  english/phonetics/audio/*.mp3        + english/phonetics/data/audio.js  (window.PHON_AUDIO)
  english/irregular-verbs/audio/*.mp3  + english/irregular-verbs/audio-data.js (window.VERB_AUDIO)
"""
import hashlib, json, os, subprocess, sys, tempfile, time, urllib.request, urllib.error
from xml.sax.saxutils import escape, quoteattr

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
JOBS = json.load(open(os.path.join(ROOT, "tools/audio/jobs.json"), encoding="utf-8"))
KEY = os.environ.get("AZURE_SPEECH_KEY", "").strip()
REGION = os.environ.get("AZURE_SPEECH_REGION", "").strip().lower().replace(" ", "")
VOICE = {"bre": os.environ.get("VOICE_BRE", "en-GB-SoniaNeural"), "ga": os.environ.get("VOICE_GA", "en-US-AvaNeural")}
LANG = {"bre": "en-GB", "ga": "en-US"}
RATE = os.environ.get("TTS_RATE", "-8%")
SETS = {
    "phonetics": {"dir": "english/phonetics/audio", "map": "english/phonetics/data/audio.js", "var": "PHON_AUDIO",
                  "head": "/* Word and sentence audio (Azure neural voices: British en-GB, American en-US for keys starting with ga:). Generated by tools/audio – do not edit. */"},
    "verbs": {"dir": "english/irregular-verbs/audio", "map": "english/irregular-verbs/audio-data.js", "var": "VERB_AUDIO",
              "head": "/* Pre-recorded British English pronunciation (Azure neural voice), one MP3 file per spoken form in audio/. Generated by tools/audio – do not edit. */"},
}
MIN_GAP = float(os.environ.get("MIN_GAP", "3.2"))  # free tier: about 20 requests per minute
_last = [0.0]


def ffmpeg_clean(src, dst):
    af = ("silenceremove=start_periods=1:start_threshold=-50dB:start_silence=0.05,"
          "areverse,silenceremove=start_periods=1:start_threshold=-50dB:start_silence=0.15,areverse,"
          "loudnorm=I=-18:TP=-2:LRA=7")
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", src, "-ac", "1", "-ar", "24000", "-af", af,
                    "-codec:a", "libmp3lame", "-b:a", "48k", dst], check=True)


def ssml(job):
    inner = escape(job["text"])
    if job.get("ipa"):
        inner = f"<phoneme alphabet=\"ipa\" ph={quoteattr(job['ipa'])}>{inner}</phoneme>"
    return (f"<speak version=\"1.0\" xmlns=\"http://www.w3.org/2001/10/synthesis\" xml:lang=\"{LANG[job['accent']]}\">"
            f"<voice name=\"{VOICE[job['accent']]}\"><prosody rate=\"{RATE}\">{inner}</prosody></voice></speak>").encode("utf-8")


def synth(job, path):
    for attempt in range(8):
        wait = MIN_GAP - (time.time() - _last[0])
        if wait > 0: time.sleep(wait)
        _last[0] = time.time()
        req = urllib.request.Request(f"https://{REGION}.tts.speech.microsoft.com/cognitiveservices/v1", data=ssml(job), method="POST",
                                     headers={"Ocp-Apim-Subscription-Key": KEY, "Content-Type": "application/ssml+xml",
                                              "X-Microsoft-OutputFormat": "audio-48khz-96kbitrate-mono-mp3", "User-Agent": "LanguageDojoAudio"})
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                raw = r.read()
            break
        except urllib.error.HTTPError as e:
            if e.code == 429 or e.code >= 500:
                time.sleep(10 * (attempt + 1)); continue
            if e.code == 400 and job.get("ipa"):  # IPA not accepted: fall back to plain text
                print(f"  IPA rejected for {job['text']}, using plain text"); job = dict(job, ipa=None); continue
            raise SystemExit(f"Azure error {e.code} for '{job['text']}': {e.read()[:300]!r}")
    else:
        raise SystemExit(f"Azure kept refusing '{job['text']}' (rate limit)")
    with tempfile.NamedTemporaryFile(suffix=".mp3", delete=False) as f:
        f.write(raw)
    ffmpeg_clean(f.name, path); os.unlink(f.name)


def main():
    if not KEY or not REGION:
        raise SystemExit("AZURE_SPEECH_KEY / AZURE_SPEECH_REGION are not set (repository secrets).")
    only = set(os.environ.get("ONLY_SETS", "phonetics,verbs").split(","))
    made = reused = 0
    for name, cfg in SETS.items():
        if name not in only: continue
        out = os.path.join(ROOT, cfg["dir"]); os.makedirs(out, exist_ok=True)
        amap = {}
        for job in [j for j in JOBS if j["set"] == name]:
            sig = f"{VOICE[job['accent']]}|{RATE}|{job['text']}|{job.get('ipa') or ''}"
            fn = hashlib.sha1(sig.encode()).hexdigest()[:12] + ".mp3"
            path = os.path.join(out, fn)
            if os.path.exists(path): reused += 1
            else:
                synth(job, path); made += 1
                if made % 25 == 0: print(f"  {made} generated…", flush=True)
            amap[job["key"]] = fn
        used = set(amap.values())
        for f in os.listdir(out):
            if f.endswith(".mp3") and f not in used: os.remove(os.path.join(out, f))
        with open(os.path.join(ROOT, cfg["map"]), "w", encoding="utf-8") as f:
            f.write(cfg["head"] + "\nwindow." + cfg["var"] + " = " + json.dumps(amap, ensure_ascii=False, separators=(",", ":")) + ";\n")
        print(f"{name}: {len(amap)} items")
    print(f"generated {made}, reused {reused}")


if __name__ == "__main__":
    main()
